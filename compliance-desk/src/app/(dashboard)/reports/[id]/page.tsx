"use client"

import { useState, useEffect, useCallback } from "react"
import { useParams, useRouter, useSearchParams } from "next/navigation"
import { usePageTitle } from "@/lib/use-page-title"
import { api } from "@/lib/api"
import { ArrowLeft, Printer, CheckCircle, XCircle, AlertTriangle, FileText, ChevronDown, ChevronRight } from "lucide-react"

export default function ReportDetailPage() {
  const { id } = useParams() as { id: string }
  const router = useRouter()
  const searchParams = useSearchParams()
  const autoPrint = searchParams.get("print") === "true"
  
  const [report, setReport] = useState<any>(null)
  const [isLoading, setIsLoading] = useState(true)
  const [expandedDocs, setExpandedDocs] = useState<Record<string, boolean>>({})

  usePageTitle(report?.name || "Report Detail")

  const fetchReport = useCallback(async () => {
    setIsLoading(true)
    const { data } = await api.get(`/api/reports/${id}`)
    if (data) setReport(data)
    setIsLoading(false)
  }, [id])

  useEffect(() => {
    fetchReport()
  }, [fetchReport])

  useEffect(() => {
    if (autoPrint && report && report.status === "READY") {
      // Small delay to allow rendering
      const t = setTimeout(() => window.print(), 500)
      return () => clearTimeout(t)
    }
  }, [autoPrint, report])

  if (isLoading) {
    return (
      <div className="space-y-6 animate-pulse p-6">
        <div className="h-8 bg-surface rounded w-1/3" />
        <div className="h-32 bg-surface rounded w-full" />
        <div className="h-64 bg-surface rounded w-full" />
      </div>
    )
  }

  if (!report) {
    return <div className="p-6 text-center text-text-muted">Report not found</div>
  }

  if (report.status === "GENERATING") {
    return (
      <div className="p-12 text-center flex flex-col items-center">
        <div className="w-12 h-12 border-4 border-green-500 border-t-transparent rounded-full animate-spin mb-4" />
        <h2 className="text-xl font-semibold mb-2">Generating Report...</h2>
        <p className="text-text-muted">Please check back in a few moments.</p>
        <button onClick={() => router.push("/reports")} className="mt-6 text-green-400 hover:underline">
          Back to Reports
        </button>
      </div>
    )
  }

  const toggleDoc = (docId: string) => {
    setExpandedDocs(prev => ({ ...prev, [docId]: !prev[docId] }))
  }

  const { summary, sectionBreakdown, documentResults } = report

  return (
    <div className="animate-fade-up pb-12 report-container">
      {/* Header (Hidden when printing) */}
      <div className="flex items-center justify-between mb-8 print:hidden">
        <button 
          onClick={() => router.push("/reports")}
          className="flex items-center text-sm text-text-muted hover:text-text-primary transition-colors"
        >
          <ArrowLeft className="h-4 w-4 mr-2" />
          Back to Reports
        </button>
        <button
          onClick={() => window.print()}
          className="flex items-center gap-2 px-4 py-2 bg-surface border border-border rounded-lg hover:bg-elevated transition-colors text-sm font-medium"
        >
          <Printer className="h-4 w-4" />
          Print / Save as PDF
        </button>
      </div>

      {/* Print Header */}
      <div className="hidden print:block text-center mb-8 pb-4 border-b border-border">
        <h1 className="text-2xl font-bold mb-1">{report.name}</h1>
        <p className="text-xs text-text-muted">Generated by {report.generatedBy?.name} on {new Date(report.completedAt).toLocaleDateString()}</p>
        {report.checklistName && <p className="text-xs text-text-muted mt-1">Checklist Filter: {report.checklistName}</p>}
      </div>

      {/* Report Title (Screen) */}
      <div className="mb-8 print:hidden">
        <h1 className="text-3xl font-display font-bold mb-2 text-text-primary">{report.name}</h1>
        <p className="text-sm text-text-muted">
          Generated on {new Date(report.completedAt).toLocaleDateString()} by {report.generatedBy?.name}
        </p>
      </div>

      <div className="space-y-8">
        {/* SUMMARY CARDS */}
        <div className="grid grid-cols-1 md:grid-cols-4 gap-4">
          <div className="bg-surface border border-border rounded-xl p-5 flex flex-col justify-center items-center text-center">
            <p className="text-sm text-text-muted mb-1">Overall Score</p>
            <p className={`text-4xl font-bold ${summary.averageScore >= 70 ? 'text-green-400' : 'text-red-400'}`}>
              {summary.averageScore}%
            </p>
          </div>
          <div className="bg-surface border border-border rounded-xl p-5 text-center flex flex-col justify-center">
            <p className="text-sm text-text-muted mb-1">Documents Analyzed</p>
            <p className="text-3xl font-bold text-text-primary">{summary.totalDocuments}</p>
          </div>
          <div className="bg-surface border border-border rounded-xl p-5 flex flex-col justify-center gap-2">
            <div className="flex justify-between text-sm">
              <span className="flex items-center text-green-400"><CheckCircle className="h-4 w-4 mr-1"/> Compliant</span>
              <span className="font-bold">{summary.compliantCount}</span>
            </div>
            <div className="flex justify-between text-sm">
              <span className="flex items-center text-red-400"><XCircle className="h-4 w-4 mr-1"/> Non-compliant</span>
              <span className="font-bold">{summary.nonCompliantCount}</span>
            </div>
            {/* Visual Bar */}
            <div className="w-full h-2 rounded-full overflow-hidden flex bg-surface border border-border mt-1">
              <div style={{ width: `${(summary.compliantCount / summary.totalDocuments) * 100}%` }} className="bg-green-500 h-full" />
              <div style={{ width: `${(summary.nonCompliantCount / summary.totalDocuments) * 100}%` }} className="bg-red-500 h-full" />
            </div>
          </div>
          <div className="bg-surface border border-border rounded-xl p-4 text-xs flex flex-col justify-center gap-2">
            <div>
              <p className="text-text-muted mb-0.5">Highest Score</p>
              <div className="flex justify-between">
                <span className="truncate pr-2 font-medium" title={summary.highestScore.documentName}>{summary.highestScore.documentName || 'N/A'}</span>
                <span className="text-green-400 font-bold">{summary.highestScore.score >= 0 ? summary.highestScore.score + '%' : '-'}</span>
              </div>
            </div>
            <div className="border-t border-border pt-2">
              <p className="text-text-muted mb-0.5">Lowest Score</p>
              <div className="flex justify-between">
                <span className="truncate pr-2 font-medium" title={summary.lowestScore.documentName}>{summary.lowestScore.documentName || 'N/A'}</span>
                <span className="text-red-400 font-bold">{summary.lowestScore.score <= 100 ? summary.lowestScore.score + '%' : '-'}</span>
              </div>
            </div>
          </div>
        </div>

        {/* SECTION BREAKDOWN */}
        {sectionBreakdown && sectionBreakdown.length > 0 && (
          <div className="bg-surface border border-border rounded-xl overflow-hidden">
            <div className="px-5 py-4 border-b border-border bg-elevated">
              <h2 className="text-lg font-semibold">Section Breakdown</h2>
            </div>
            <div className="p-0 overflow-x-auto">
              <table className="w-full text-sm text-left">
                <thead className="bg-base border-b border-border">
                  <tr>
                    <th className="px-5 py-3 font-medium text-text-muted">Section / Checklist</th>
                    <th className="px-5 py-3 font-medium text-text-muted w-24 text-center">Avg Score</th>
                    <th className="px-5 py-3 font-medium text-text-muted w-24 text-center">Passed</th>
                    <th className="px-5 py-3 font-medium text-text-muted w-24 text-center">Failed</th>
                    <th className="px-5 py-3 font-medium text-text-muted w-24 text-center">Warnings</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-border">
                  {sectionBreakdown.map((sec: any, idx: number) => (
                    <tr key={idx}>
                      <td className="px-5 py-3 font-medium">{sec.sectionTitle}</td>
                      <td className="px-5 py-3 text-center">
                        <span className={`inline-flex items-center px-2 py-0.5 rounded text-xs font-medium border ${sec.averageScore >= 70 ? 'text-green-400 bg-green-900/30 border-green-900/50' : 'text-red-400 bg-red-900/30 border-red-900/50'}`}>
                          {sec.averageScore}%
                        </span>
                      </td>
                      <td className="px-5 py-3 text-center text-green-400">{sec.passCount}</td>
                      <td className="px-5 py-3 text-center text-red-400">{sec.failCount}</td>
                      <td className="px-5 py-3 text-center text-amber-400">{sec.warningCount}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
        )}

        {/* DOCUMENT RESULTS */}
        <div className="bg-surface border border-border rounded-xl overflow-hidden print-break-inside-avoid">
          <div className="px-5 py-4 border-b border-border bg-elevated">
            <h2 className="text-lg font-semibold">Document Analysis Results</h2>
          </div>
          <div className="p-0">
            {documentResults && documentResults.map((doc: any, i: number) => (
              <div key={doc.documentId} className={`border-b border-border last:border-0 ${i % 2 === 0 ? 'bg-base/30' : 'bg-transparent'}`}>
                {/* Row Header */}
                <div 
                  className="px-5 py-4 flex items-center justify-between cursor-pointer hover:bg-elevated transition-colors"
                  onClick={() => toggleDoc(doc.documentId)}
                >
                  <div className="flex items-center gap-3">
                    <button className="text-text-muted hover:text-text-primary print:hidden">
                      {expandedDocs[doc.documentId] || autoPrint ? <ChevronDown className="h-4 w-4" /> : <ChevronRight className="h-4 w-4" />}
                    </button>
                    <div>
                      <h4 className="font-medium flex items-center gap-2">
                        <FileText className="h-4 w-4 text-text-muted print:hidden" />
                        {doc.documentName}
                      </h4>
                      <p className="text-xs text-text-muted mt-1 print:hidden">
                        Click to view {doc.findings ? 'findings' : 'sections'}
                      </p>
                    </div>
                  </div>
                  <div className="flex items-center gap-4">
                    <span className={`text-xs font-semibold px-2 py-1 rounded border ${doc.status === 'COMPLIANT' ? 'text-green-400 bg-green-900/30 border-green-900/50' : 'text-red-400 bg-red-900/30 border-red-900/50'}`}>
                      {doc.status.replace("_", " ")}
                    </span>
                    <span className="font-bold text-lg">{doc.score}%</span>
                  </div>
                </div>

                {/* Expanded Content */}
                {(expandedDocs[doc.documentId] || autoPrint) && (
                  <div className="px-10 py-4 bg-base/50 border-t border-border">
                    {/* Findings Table */}
                    {doc.findings && doc.findings.length > 0 ? (
                      <table className="w-full text-xs text-left">
                        <thead className="text-text-muted border-b border-border">
                          <tr>
                            <th className="py-2 w-1/4">Clause / Requirement</th>
                            <th className="py-2 w-20">Result</th>
                            <th className="py-2">Details</th>
                          </tr>
                        </thead>
                        <tbody className="divide-y divide-border/50">
                          {doc.findings.map((finding: any, fIdx: number) => (
                            <tr key={fIdx} className="align-top">
                              <td className="py-3 font-medium text-text-secondary">{finding.clause}</td>
                              <td className="py-3">
                                {finding.result === 'PASS' && <span className="text-green-400 flex items-center"><CheckCircle className="h-3 w-3 mr-1"/> Pass</span>}
                                {finding.result === 'FAIL' && <span className="text-red-400 flex items-center"><XCircle className="h-3 w-3 mr-1"/> Fail</span>}
                                {finding.result !== 'PASS' && finding.result !== 'FAIL' && <span className="text-amber-400 flex items-center"><AlertTriangle className="h-3 w-3 mr-1"/> Warn</span>}
                              </td>
                              <td className="py-3">
                                <p className="text-text-secondary">{finding.detail}</p>
                                {finding.recommendation && (
                                  <div className="mt-2 p-2 bg-amber-900/10 border border-amber-900/30 rounded text-amber-400/90 text-[11px]">
                                    <span className="font-bold block mb-0.5">Recommendation:</span>
                                    {finding.recommendation}
                                  </div>
                                )}
                              </td>
                            </tr>
                          ))}
                        </tbody>
                      </table>
                    ) : (
                      <p className="text-sm text-text-muted">No detailed findings available.</p>
                    )}
                  </div>
                )}
              </div>
            ))}
          </div>
        </div>
      </div>
    </div>
  )
}
